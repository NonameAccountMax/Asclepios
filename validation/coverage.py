#!/usr/bin/env python3
"""Coverage of the validation suite: what asclepios reads that no validation case exercises, and what the cases use
that asclepios does not read.

Compares the keywords and element types recognised by the input reader (src/model/model.cpp, src/inp/parser.cpp)
with those used by the decks run by asclepios (cases marked supported in cases/manifest.json). Writes COVERAGE.md:
  - keywords handled by asclepios but used in no case run by asclepios (untested features);
  - keywords accepted and ignored by asclepios;
  - keywords used by a case run by asclepios but not recognised by the reader (silently ignored);
  - element types accepted, and those computed with the formulation of another type (substitutions).
Every new feature or fix of the solver should come with a case, so that the first list stays empty or justified.

usage: coverage.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def reader_keywords():
    src = open(os.path.join(ROOT, 'src', 'model', 'model.cpp')).read()
    handled = set(re.findall(r'k == "([A-Z][A-Z ,\-]+)"', src))
    handled |= set(re.findall(r'keyword == "([A-Z][A-Z ]+)"', open(os.path.join(ROOT, 'src', 'inp', 'parser.cpp')).read()))
    handled |= {'CONNECTOR ' + k for k in re.findall(r'"CONNECTOR ([A-Z ]+)"', src)}
    ignored = set()
    for cond in re.findall(r'else if \(([^{}]*?)\) \{\s*(?://[^\n]*)?\s*\}', src, re.S):  # empty branches
        ignored |= set(re.findall(r'k == "([A-Z][A-Z ]+)"', cond))
    # material options dispatched to card_material_sub but without a branch there: accepted, not implemented
    body = src[src.index('void card_material_sub'):]
    body = body[:body.index('\n  }\n')]
    disp = re.search(r'ctx == CTX_MATERIAL && \((.*?)\)\) \{', src, re.S)
    if disp:
        for k in re.findall(r'k == "([A-Z][A-Z ]+)"', disp.group(1)):
            if '"%s"' % k not in body:
                ignored.add(k)
    inter = re.search(r'k == "FRICTION" \|\| k == "SURFACE BEHAVIOR" \|\| k == "CONTACT DAMPING"', src)
    if inter:
        ignored |= {'SURFACE BEHAVIOR', 'CONTACT DAMPING'}
    return handled, ignored


def reader_elements():
    src = open(os.path.join(ROOT, 'src', 'model', 'model.cpp')).read()
    body = src[src.index('ElType eltype_from'):src.index('ElType::UNKNOWN', src.index('ElType eltype_from'))]
    accepted, alias = set(), {}
    for names, target in re.findall(r'if \(([^)]*)\) \{ nn = \d+; return ElType::(\w+); \}', body):
        for n in re.findall(r'"(\w+)"', names):
            accepted.add(n)
            if n != target:
                alias[n] = target
    groups = open(os.path.join(ROOT, 'src', 'element', 'groups.cpp')).read()
    ignored = set(re.findall(r'ElType::(\w+)\) \{ warn\("[^"]*not supported', groups))
    return accepted, alias, ignored


def deck_keywords(path):
    out = set()
    for line in open(path, errors='replace'):
        if line.startswith('*') and not line.startswith('**'):
            out.add(line[1:].split(',')[0].strip().upper())
            if line.lower().startswith('*include'):
                inc = line.split('=', 1)[1].strip()
                out |= deck_keywords(os.path.join(HERE, 'cases', inc))
    return out


def deck_elements(path):
    return set(m.upper() for m in re.findall(r'^\*Element, type=(\w+)', open(path).read(), re.M | re.I))


def main():
    cases = json.load(open(os.path.join(HERE, 'cases', 'manifest.json')))
    handled, ignored = reader_keywords()
    accepted, alias, el_ignored = reader_elements()
    used_run, used_all, el_run = {}, set(), {}
    for c in cases:
        p = os.path.join(HERE, 'cases', c['name'] + '.inp')
        kws = deck_keywords(p)
        used_all |= kws
        if c.get('supported', True):
            for k in kws:
                used_run.setdefault(k, []).append(c['name'])
            for e in deck_elements(p):
                el_run.setdefault(e, []).append(c['name'])
    structural = handled - ignored - {'INCLUDE', 'PARAMETER', 'HEADING', 'END PART', 'END INSTANCE', 'END ASSEMBLY',
                                      'END STEP', 'STEP', 'NODE', 'ELEMENT'}
    untested = sorted(k for k in structural if k not in used_run)
    silent = sorted(k for k in used_run if k not in handled and k not in ignored)
    lines = ['# Validation coverage', '',
             'Generated by `validation/coverage.py` (run by `make validate`). Keywords and element types read by '
             'asclepios, compared with those used by the %d cases run by asclepios.' % sum(1 for c in cases
                                                                                         if c.get('supported', True)),
             '', '## Keywords handled by asclepios and exercised by no case', '']
    lines += ['- `*%s`' % k for k in untested] or ['None.']
    lines += ['', '## Keywords used by cases run by asclepios but not recognised by the reader (ignored)', '']
    lines += ['- `*%s` (%s)' % (k, ', '.join(sorted(used_run[k])[:4])) for k in silent] or ['None.']
    lines += ['', '## Keywords accepted and ignored by asclepios', '', ', '.join('`*%s`' % k for k in sorted(ignored)), '',
              '## Element types', '', '| Type | Computed as | Cases run by asclepios |', '|---|---|---|']
    for e in sorted(accepted):
        tgt = alias.get(e, e)
        note = 'ignored (not implemented)' if tgt in el_ignored else (tgt if e in alias else '')
        lines.append('| %s | %s | %d |' % (e, note, len(el_run.get(e, []))))
    with open(os.path.join(HERE, 'COVERAGE.md'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('coverage: %d keywords handled and untested, %d used but not recognised, %d element types without a case'
          % (len(untested), len(silent), sum(1 for e in accepted if not el_run.get(e))))
    for k in untested:
        print('  untested keyword *%s' % k)
    for k in silent:
        print('  keyword *%s used by a case run by asclepios but not recognised' % k)


if __name__ == '__main__':
    main()
