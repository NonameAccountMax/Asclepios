#!/usr/bin/env python3
"""Solver checks: parallel runs (results independent of the number of threads, speed-up), reproducibility (two
identical runs give identical results), restart (a run resumed from a restart file reproduces the uninterrupted run
bit for bit), and run time against the model size, with the Abaqus timings of the reference machine.

Runs a few cases with 1, 2, 4, ... threads (up to the number of cores), compares every run with the single-thread run
(displacements and rotations of the monitored nodes, reaction forces, energies; peak-normalised differences) and writes
PARALLEL.md. When Abaqus timings exist (reference/<case>.time and reference/<case>__cpus4.time, written by
abaqus/run_references.sh), they are listed too.

usage: parallel.py [case ...] [--threads 1,2,4,8]
"""
import json
import os
import subprocess
import sys
import time

import compare

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'out', 'parallel')
CASES = ['par_plate_pulse', 'par_block_static', 'contact_friction_sliding', 'c3d8r_wave']
TOL = 1e-6  # relative difference allowed between thread counts (summation order only)


def run(case, nthreads, tag='', extra=None, env=None):
    wd = os.path.join(OUT, '%s_j%d%s' % (case['name'], nthreads, tag))
    os.makedirs(wd, exist_ok=True)
    t0 = time.time()
    r = subprocess.run([compare.BIN, os.path.join(compare.CASES, case['name'] + '.inp'), '-q', '-j', str(nthreads)] +
                       (extra or []), cwd=wd, capture_output=True, text=True, env=env)
    dt = time.time() - t0
    if r.returncode != 0:
        return None, dt
    saved = compare.OUT
    compare.OUT = wd
    try:
        res = compare.asclepios_results(case)
    finally:
        compare.OUT = saved
    return res, dt


def difference(a, b):
    errs = [compare.field_error(a, b, 'U'), compare.field_error(a, b, 'UR'), compare.rf_error(a, b),
            compare.energy_error(a, b)]
    errs = [e for e in errs if e is not None]
    return max(errs) if errs else 0.0


def abaqus_time(name, suffix=''):
    p = os.path.join(compare.REF, name + suffix + '.time')
    return float(open(p).read().split()[0]) if os.path.exists(p) else None


def main():
    args = sys.argv[1:]
    ncores = os.cpu_count() or 4
    threads = [1, 2, 4, 8, 16]
    if '--threads' in args:
        threads = [int(x) for x in args[args.index('--threads') + 1].split(',')]
    threads = [n for n in threads if n <= ncores]
    names = [a for i, a in enumerate(args) if not a.startswith('--') and (i == 0 or args[i - 1] != '--threads')]
    manifest = {c['name']: c for c in json.load(open(os.path.join(compare.CASES, 'manifest.json')))}
    cases = [manifest[n] for n in (names or CASES)]
    lines = ['# Parallel runs', '',
             'Generated by `validation/parallel.py` (`make parallel`) on a machine with %d cores. Each case is run with '
             'an increasing number of threads; the difference with the single-thread run is the largest peak-normalised '
             'difference of displacements, rotations, reaction forces and energies (allowed: %g).' % (ncores, TOL), '',
             '| Case | Threads | Wall time (s) | Speed-up | Difference with 1 thread | Status |', '|---|---|---|---|---|---|']
    bad = 0
    for c in cases:
        base, t1 = None, None
        for n in threads:
            res, dt = run(c, n)
            if res is None:
                lines.append('| `%s` | %d | %.2f | | | RUN FAILED |' % (c['name'], n, dt))
                bad += 1
                print('%-26s %2d threads  RUN FAILED' % (c['name'], n))
                continue
            if n == threads[0]:
                base, t1 = res, dt
                diff = 0.0
            else:
                diff = difference(res, base)
            ok = diff <= TOL
            bad += not ok
            lines.append('| `%s` | %d | %.2f | %.2f | %.1e | %s |' % (c['name'], n, dt, t1 / dt if t1 else 0, diff,
                                                                       'PASS' if ok else 'FAIL'))
            print('%-26s %2d threads  %7.2f s  speed-up %5.2f  diff %.1e  %s' % (c['name'], n, dt, t1 / dt, diff,
                                                                                'PASS' if ok else 'FAIL'))
    # reproducibility and restart
    lines += ['', '## Reproducibility and restart', '', '| Check | Case | Difference | Status |', '|---|---|---|---|']
    nt = min(4, ncores)
    for name in ('par_plate_pulse', 'contact_friction_sliding'):
        c = manifest[name]
        a, _ = run(c, nt, '_rep1')
        b, _ = run(c, nt, '_rep2')
        diff = difference(a, b) if a and b else float('inf')
        bad += diff > 1e-12
        lines.append('| two identical runs (allowed: 1e-12, summation order of the threads) | `%s` | %.1e | %s |'
                     % (name, diff, 'PASS' if diff <= 1e-12 else 'FAIL'))
        print('%-26s reproducibility diff %.1e' % (name, diff))
    # shells (element bound of the increment) and solids (global estimate of the increment)
    for name, tsave in (('par_plate_pulse', 1e-4), ('c3d8r_wave', 1.6e-5)):
        c = manifest[name]
        env = dict(os.environ, ABQ_KEEP_RESTARTS='1')
        full, _ = run(c, nt, '_full', ['save=%g' % tsave], env)
        wd_full = os.path.join(OUT, '%s_j%d_full' % (c['name'], nt))
        rst = os.path.join(wd_full, '%s_t%.6f.rst' % (c['name'], tsave))
        resumed = None
        if full and os.path.exists(rst):
            resumed, _ = run(c, nt, '_resumed', ['restart=' + rst])
        if resumed:  # compare the frames after the restart time
            late = lambda r: {'frames': [f for f in r['frames'] if f['t'] > tsave * 1.000001], 'history': r['history']}
            diff = difference(late(resumed), late(full))
        else:
            diff = float('inf')
        bad += diff != 0.0
        lines.append('| restart at half time | `%s` | %.1e | %s |' % (c['name'], diff, 'PASS' if diff == 0.0 else 'FAIL'))
        print('%-26s restart diff %.1e' % (c['name'], diff))
    # run time against the model size
    lines += ['', '## Run time against the model size', '',
              'Explicit clamped plate under a pressure pulse (same duration). asclepios on this machine with 1 thread and '
              'with %d threads; Abaqus 2018 on the reference machine (whole job, including pre- and post-processing).'
              % nt, '', '| Case | Elements | asclepios 1 thread (s) | asclepios %d threads (s) | Abaqus 1 cpu (s) | '
              'Abaqus 4 cpus (s) | Abaqus 1 cpu, single precision (s) |' % nt, '|---|---|---|---|---|---|---|']
    for n in (20, 40, 80):
        name = 'par_perf_%d' % n
        if name not in manifest:
            continue
        c = manifest[name]
        _, t1 = run(c, 1, '_perf')
        _, tn = run(c, nt, '_perf')
        ab = [abaqus_time(name, s_) for s_ in ('', '__cpus4', '__single')]
        lines.append('| `%s` | %d | %.2f | %.2f | %s |' % (name, n * n, t1, tn, ' | '.join('%.0f' % a if a else ''
                                                                                          for a in ab)))
        print('%-26s 1 thread %.2f s, %d threads %.2f s, Abaqus %s' % (name, t1, nt, tn, ab))
    ab = [(c['name'], abaqus_time(c['name']), abaqus_time(c['name'], '__cpus4')) for c in cases]
    if any(t for _, t, _ in ab):
        lines += ['', 'Abaqus on the reference machine (wall time of the whole job, s):', '',
                  '| Case | 1 cpu | 4 cpus |', '|---|---|---|']
        lines += ['| `%s` | %s | %s |' % (n, '%.1f' % a if a else '', '%.1f' % b if b else '') for n, a, b in ab]
    with open(os.path.join(HERE, 'PARALLEL.md'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
